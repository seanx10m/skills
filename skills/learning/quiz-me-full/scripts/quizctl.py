#!/usr/bin/env python3
"""Spaced repetition over a quiz-me deck, with progress kept in plain Markdown.

    quizctl.py start   <deck.md> [--new N] [--max N]   pick due cards, open the UI
    quizctl.py sync                                    fold downloaded results in
    quizctl.py record  <<< '<json>'                    same, from a pasted blob
    quizctl.py status  <deck-id|deck.md>               what an agent should read
    quizctl.py brief   <deck-id|deck.md> [--out PATH]  narration-ready review .md

Progress lives at ~/Desktop/quiz-progress/<deck-id>.md - ONE markdown file per
deck, and the table in it IS the database. It is parsed back on every read, so
hand-editing a row works and nothing is hidden in a sidecar. Regenerated on
write, so the columns stay aligned.

The scheduler is SM-2 (Anki's classic algorithm) with one change: the grade is
derived from correctness AND the confidence stated BEFORE the answer was
revealed. Anki asks how hard recall felt after showing you the answer, which
cannot tell "knew it" from "guessed right". Asking first can, so:

    correct + sure   -> 5   knew it            interval grows fastest
    correct + think  -> 4   solid
    correct + guess  -> 3   lucky              ease drops; comes back soon
    wrong   + guess  -> 2   honest miss        gentlest reset
    wrong   + think  -> 1   wrong
    wrong   + sure   -> 0   CONFIDENTLY WRONG  hardest reset + extra ease hit

The last row is the point of the whole thing. A confident wrong model is more
expensive than an admitted gap, so it is scheduled as more urgent than one.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

RENDER = Path(__file__).resolve().parent  # deck.py, render.py, template.html are bundled here
sys.path.insert(0, str(RENDER))
from deck import LEVELS, DeckError, next_level, parse  # noqa: E402

HOME = Path.home()
PROG_DIR = HOME / "Desktop" / "quiz-progress"
DOWNLOADS = HOME / "Downloads"
LEECH_LAPSES = 8
LEECH_CONF_WRONG = 2
MAX_INTERVAL = 365
LOG_KEEP = 60

COLS = ["id", "card", "L", "reps", "lapses", "cw", "ease", "ivl", "due", "last", "state"]


# ---------------------------------------------------------------- scheduling

def grade_of(ok: bool, conf: int) -> int:
    """conf: 0=sure, 1=think so, 2=guess."""
    return {(True, 0): 5, (True, 1): 4, (True, 2): 3,
            (False, 2): 2, (False, 1): 1, (False, 0): 0}[(ok, conf)]


def schedule(row: dict, grade: int) -> dict:
    """SM-2 step. Returns a NEW row dict; does not mutate the input.

    Pure and total - every branch returns, no clock read, no I/O - so the
    six-outcome preview the UI shows is generated by calling this function
    six times rather than by a second copy of the rules in JavaScript.
    """
    r = dict(row)
    ease, reps, ivl = r["ease"], r["reps"], r["ivl"]

    if grade >= 3:
        if reps == 0:
            # Anki's easy bonus: a NEW card answered confidently graduates
            # straight past the 1-day step. Without this every first answer
            # schedules to tomorrow whatever you said, which makes the
            # interval preview on the confidence chips carry no information.
            ivl = 4 if grade == 5 else 1
        elif reps == 1:
            ivl = 6
        else:
            ivl = max(1, round(ivl * ease))
        reps += 1
    else:
        reps = 0
        r["lapses"] += 1
        # A confident miss relearns TODAY; an admitted guess gets tomorrow.
        ivl = 0 if grade == 0 else 1
        if grade == 0:
            r["cw"] += 1
            ease -= 0.35  # on top of the SM-2 penalty below

    ease = ease + (0.1 - (5 - grade) * (0.08 + (5 - grade) * 0.02))
    r["ease"] = max(1.3, round(ease, 2))
    r["reps"] = reps
    r["ivl"] = min(ivl, MAX_INTERVAL)
    return r


def state_of(r: dict) -> str:
    if r["cw"] >= LEECH_CONF_WRONG or r["lapses"] >= LEECH_LAPSES:
        return "leech"
    if r["reps"] == 0:
        return "new" if r["last"] == "-" else "relearn"
    if r["ivl"] >= 21:
        return "mature"
    return "young"


def human_ivl(days: int) -> str:
    if days <= 0:
        return "today"
    if days == 1:
        return "tomorrow"
    if days < 30:
        return f"{days}d"
    if days < 365:
        return f"{round(days/30.4)}mo"
    return f"{round(days/365, 1)}y"


# ---------------------------------------------------------- progress.md store

def prog_path(deck_id: str) -> Path:
    return PROG_DIR / f"{deck_id}.md"


def blank_row(card: dict) -> dict:
    return {"id": card["id"], "card": label(card), "L": card["d"], "reps": 0,
            "lapses": 0, "cw": 0, "ease": 2.5, "ivl": 0, "due": "-",
            "last": "-", "state": "new"}


def label(card: dict) -> str:
    t = re.sub(r"`|\*\*|\|", "", card["q"]).strip()
    return (t[:52] + "...") if len(t) > 55 else t


def load(deck: dict) -> dict:
    """Read progress for a deck, seeding rows for any card not yet tracked."""
    p = prog_path(deck["id"])
    rows: dict[int, dict] = {}
    level, log = 1, []
    if p.is_file():
        text = p.read_text(encoding="utf-8")
        m = re.search(r"^level:\s*([1-5])", text, re.M)
        if m:
            level = int(m.group(1))
        for line in text.splitlines():
            if not line.startswith("| ") or line.startswith("| id ") or set(line) <= set("|- "):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) != len(COLS) or not cells[0].isdigit():
                continue
            d = dict(zip(COLS, cells))
            try:
                rows[int(d["id"])] = {
                    "id": int(d["id"]), "card": d["card"], "L": int(d["L"]),
                    "reps": int(d["reps"]), "lapses": int(d["lapses"]),
                    "cw": int(d["cw"]), "ease": float(d["ease"]),
                    "ivl": int(d["ivl"]), "due": d["due"], "last": d["last"],
                    "state": d["state"]}
            except ValueError:
                continue  # a hand-edit we cannot read is skipped, never fatal
        log = [l for l in text.splitlines() if l.startswith("- 20")]
    for c in deck["cards"]:
        if c["id"] not in rows:
            rows[c["id"]] = blank_row(c)
        else:
            rows[c["id"]]["card"] = label(c)  # deck text is authoritative
            rows[c["id"]]["L"] = c["d"]
    return {"rows": rows, "level": level, "log": log}


def save(deck: dict, st: dict) -> Path:
    PROG_DIR.mkdir(parents=True, exist_ok=True)
    rows = [st["rows"][k] for k in sorted(st["rows"])]
    for r in rows:
        r["state"] = state_of(r)
    today = date.today().isoformat()
    due = [r for r in rows if r["due"] != "-" and r["due"] <= today]
    new = [r for r in rows if r["state"] == "new"]
    leech = [r for r in rows if r["state"] == "leech"]
    seen = [r for r in rows if r["last"] != "-"]
    lname = LEVELS[st["level"]][0]

    w = [max(len(c), *(len(str(r[c])) for r in rows)) for c in COLS] if rows else []
    def line(vals):
        return "| " + " | ".join(str(v).ljust(w[i]) for i, v in enumerate(vals)) + " |"

    out = [
        f"# {deck['title']} - quiz progress",
        "",
        f"deck: {deck['id']}",
        f"level: {st['level']}   <!-- 1-5, the adaptive ladder; edit to force a level -->",
        f"source: {deck['path']}",
        f"updated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        "",
        "## Where you are",
        "",
        f"- **Level {st['level']} - {lname}.** {LEVELS[st['level']][1]}.",
        f"- **{len(due)} due now**, {len(new)} never seen, {len(rows)} cards total.",
        f"- Seen at least once: {len(seen)}/{len(rows)}.",
        f"- Confidently wrong at least twice, or 8+ lapses (**leeches**): {len(leech)}"
        + (f" - {', '.join('#' + str(r['id']) for r in leech)}" if leech else ""),
        "",
        "## Cards",
        "",
        line(COLS),
        "|" + "|".join("-" * (x + 2) for x in w) + "|",
        *[line([r[c] for c in COLS]) for r in rows],
        "",
        "`L` = difficulty 1-5 (from the deck). `cw` = times you were confidently wrong -",
        "the column that matters most. `ease` starts at 2.50 and falls as a card fights you.",
        "`ivl` is days until the next showing.",
        "",
        "## Log",
        "",
        *st["log"][-LOG_KEEP:],
        "",
    ]
    p = prog_path(deck["id"])
    p.write_text("\n".join(out), encoding="utf-8")
    return p


# --------------------------------------------------------------- the commands

def pick(deck: dict, st: dict, new_cap: int, max_cards: int,
         ignore_due: bool = False) -> list[dict]:
    """Due first, then new cards near the current level.

    Anki picks purely by due date. The level ladder adds one rule on top: a
    NEW card is only introduced if it sits within one rung of where you are,
    so the deck feeds you harder material as you earn it instead of all at once.
    """
    today = date.today().isoformat()
    rows = st["rows"]
    lvl = st["level"]
    due = [r for r in rows.values() if r["due"] != "-"
           and (ignore_due or r["due"] <= today)]
    due.sort(key=lambda r: (r["state"] != "leech", r["due"], -r["cw"]))

    fresh = [r for r in rows.values() if r["last"] == "-" and abs(r["L"] - lvl) <= 1]
    fresh.sort(key=lambda r: (abs(r["L"] - lvl), r["L"], r["id"]))
    if not due and not fresh:  # nothing due and nothing in band - widen rather than stall
        fresh = sorted((r for r in rows.values() if r["last"] == "-"),
                       key=lambda r: (r["L"], r["id"]))

    chosen = due + fresh[:new_cap]
    return chosen[:max_cards]


def cmd_start(a) -> int:
    d = parse(a.deck)
    st = load(d)
    # Write the progress file BEFORE the session, not after. It is what records
    # `source:`, and `sync` resolves the deck through that line - so a first run
    # that only wrote on completion could never be synced back.
    save(d, st)
    rows = pick(d, st, a.new, a.max, ignore_due=getattr(a, "all", False))
    if not rows:
        nxt = sorted(r["due"] for r in st["rows"].values() if r["due"] != "-")
        print(f"Nothing due for '{d['id']}'."
              + (f" Next card is due {nxt[0]}." if nxt else ""))
        print(f"Force a run with: quizctl.py start {a.deck} --all")
        return 0

    sched = {}
    for r in rows:
        prev = {("r" if ok else "w") + str(conf):
                human_ivl(schedule(r, grade_of(ok, conf))["ivl"])
                for ok in (True, False) for conf in (0, 1, 2)}
        sched[str(r["id"])] = prev

    session = datetime.now().strftime("%Y%m%d-%H%M%S")
    cfg = {"scheduled": True, "session": session, "level": st["level"],
           "sched": sched, "kicker": f"{d['title']} · Level {st['level']}",
           "subtitle": f"{len(rows)} cards due. Say how sure you were BEFORE the "
                       "answer is explained - that is what schedules the next showing.",
           "syncCmd": "quiz-me-full sync"}
    (PROG_DIR / ".rendered").mkdir(parents=True, exist_ok=True)
    cfg_path = PROG_DIR / ".rendered" / f"{d['id']}.cfg.json"
    cfg_path.write_text(json.dumps(cfg))

    cmd = [sys.executable, str(RENDER / "render.py"), str(Path(a.deck).resolve()),
           "--cards", ",".join(str(r["id"]) for r in rows),
           "--config", str(cfg_path)]
    if a.no_open:
        cmd.append("--no-open")
    subprocess.run(cmd, check=True)
    dues = sum(1 for r in rows if r["last"] != "-")
    print(f"\nSession {session}: {len(rows)} cards "
          f"({dues} review, {len(rows)-dues} new) at level {st['level']} "
          f"- {LEVELS[st['level']][0]}")
    print("When you finish, click Download and run:  quiz-me-full sync")
    return 0


def apply_result(payload: dict) -> str:
    """Fold one finished session into its progress file. Returns a report line."""
    deck_id = payload["deck"]
    p = prog_path(deck_id)
    src = None
    if p.is_file():
        m = re.search(r"^source:\s*(.+)$", p.read_text(encoding="utf-8"), re.M)
        if m:
            src = m.group(1).strip()
    if not src or not Path(src).is_file():
        raise SystemExit(f"cannot find the deck for '{deck_id}' "
                         f"(expected `source:` in {p}). Run `start` once first.")
    d = parse(src)
    st = load(d)
    today = date.today()
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    wrong = cw = 0
    for res in payload["results"]:
        r = st["rows"].get(res["id"])
        if r is None:
            continue
        g = grade_of(res["ok"], res["conf"])
        before = r["ivl"]
        new = schedule(r, g)
        new["last"] = today.isoformat()
        new["due"] = (today + timedelta(days=max(new["ivl"], 0))).isoformat()
        new["state"] = state_of(new)
        st["rows"][res["id"]] = new
        if not res["ok"]:
            wrong += 1
            tag = "CONFIDENTLY WRONG" if res["conf"] == 0 else "wrong"
            if res["conf"] == 0:
                cw += 1
            st["log"].append(
                f"- {stamp} · #{res['id']} L{res['d']} · {tag} · "
                f"{before}d -> {human_ivl(new['ivl'])} · ease {new['ease']}")
        elif res["conf"] == 2:
            st["log"].append(
                f"- {stamp} · #{res['id']} L{res['d']} · lucky guess · "
                f"{before}d -> {human_ivl(new['ivl'])}")

    lvl, why = next_level(st["level"], [
        {"ok": r["ok"], "conf": r["conf"], "d": r["d"]} for r in payload["results"]])
    if lvl != st["level"]:
        st["log"].append(f"- {stamp} · LEVEL {st['level']} -> {lvl} · {why}")
    st["level"] = lvl
    n = len(payload["results"])
    st["log"].append(f"- {stamp} · session {payload.get('session','?')} · "
                     f"{n - wrong}/{n} correct · {cw} confidently wrong · level {lvl}")
    out = save(d, st)
    return (f"{d['title']}: {n-wrong}/{n} correct, {cw} confidently wrong, "
            f"level {lvl} ({why}) -> {out}")


def cmd_sync(a) -> int:
    hits = sorted(DOWNLOADS.glob("*.quizresult.json"), key=lambda p: p.stat().st_mtime)
    if not hits:
        print(f"No *.quizresult.json in {DOWNLOADS}. Click Download on the result "
              "screen, or pipe the copied blob into `quizctl.py record`.")
        return 1
    for f in hits:
        try:
            print(apply_result(json.loads(f.read_text())))
        except (json.JSONDecodeError, KeyError) as exc:
            print(f"skipped {f.name}: not a quiz result ({exc})")
            continue
        f.unlink()
    return 0


def cmd_record(a) -> int:
    raw = sys.stdin.read().strip()
    if not raw:
        print("nothing on stdin", file=sys.stderr)
        return 1
    print(apply_result(json.loads(raw)))
    return 0


def _resolve(target: str) -> dict:
    """Accept either a deck path or a bare deck id."""
    p = Path(target)
    if p.is_file():
        return parse(p)
    pp = prog_path(target)
    if not pp.is_file():
        raise SystemExit(f"no deck or progress file for '{target}' (looked at {pp})")
    m = re.search(r"^source:\s*(.+)$", pp.read_text(encoding="utf-8"), re.M)
    if not m:
        raise SystemExit(f"{pp} has no `source:` line")
    return parse(m.group(1).strip())


def cmd_status(a) -> int:
    d = _resolve(a.deck)
    st = load(d)
    today = date.today().isoformat()
    rows = list(st["rows"].values())
    for r in rows:
        r["state"] = state_of(r)
    due = [r for r in rows if r["due"] != "-" and r["due"] <= today]
    new = [r for r in rows if r["state"] == "new"]
    leech = [r for r in rows if r["state"] == "leech"]
    print(f"{d['title']}  ({d['id']})")
    print(f"  level    {st['level']} - {LEVELS[st['level']][0]}: {LEVELS[st['level']][1]}")
    print(f"  due now  {len(due)}   new {len(new)}   total {len(rows)}")
    print(f"  leeches  {len(leech)}"
          + (f"  -> {', '.join('#'+str(r['id'])+' '+r['card'][:34] for r in leech)}"
             if leech else ""))
    nxt = sorted(r["due"] for r in rows if r["due"] != "-" and r["due"] > today)
    if nxt:
        print(f"  next due {nxt[0]}")
    print(f"  progress {prog_path(d['id'])}")
    if st["log"]:
        print("  recent:")
        for l in st["log"][-5:]:
            print("   ", l[2:])
    return 0


def cmd_brief(a) -> int:
    """A narration-ready review of what you keep missing.

    Prose, not a table, because its job is to be read aloud by a text-to-speech tool of your choice and
    scheduled as a reminder. A table read aloud is noise.
    """
    d = _resolve(a.deck)
    st = load(d)
    by_id = {c["id"]: c for c in d["cards"]}
    rows = sorted(st["rows"].values(), key=lambda r: (-r["cw"], -r["lapses"], r["ivl"]))
    weak = [r for r in rows if r["cw"] or r["lapses"]][:6]
    today = date.today().isoformat()
    due = [r for r in rows if r["due"] != "-" and r["due"] <= today]

    # Written to be SPOKEN (a text-to-speech tool of your choice), so it has to survive being read aloud:
    # no backticks, no bare "1 cards", no table.
    def plural(n: int, one: str, many: str) -> str:
        return f"{n} {one}" if n == 1 else f"{n} {many}"

    speak = lambda s: re.sub(r"`|\*\*", "", s)  # noqa: E731

    L = [f"# {d['title']} - what to shore up",
         "",
         f"Recorded {datetime.now().strftime('%A %d %B')}. "
         f"You are at level {st['level']}, {LEVELS[st['level']][0].lower()}. "
         + (f"{plural(len(due), 'card is', 'cards are')} due today. "
            if due else "Nothing is due today. ")
         + (f"{plural(len(weak), 'question has', 'questions have')} given you trouble."
            if weak else "Nothing has given you real trouble yet."),
         ""]
    if not weak:
        L += ["Keep going - there is nothing worth re-teaching yet.", ""]
    for r in weak:
        c = by_id.get(r["id"])
        if not c:
            continue
        why = (f"You were confidently wrong on this "
               f"{plural(r['cw'], 'time', 'times')}. " if r["cw"] else
               f"You have missed this {plural(r['lapses'], 'time', 'times')}. ")
        L += [f"## {speak(c['q'])}", "",
              why + "The answer is: " + speak(c["opts"][c["a"]]).rstrip(".") + ".",
              "",
              speak(c["exp"]), ""]
        if c.get("cite"):
            L += [f"Source: {c['cite']}", ""]
    L += ["---", "",
          "Read this aloud with `a text-to-speech tool of your choice`, or schedule it as a reminder.",
          f"Re-run the quiz with: `quiz-me-full start {d['path']}`", ""]

    out = Path(a.out) if a.out else PROG_DIR / f"{d['id']}-review.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print(out)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)

    s = sp.add_parser("start"); s.add_argument("deck")
    s.add_argument("--new", type=int, default=4, help="max never-seen cards")
    s.add_argument("--max", type=int, default=12, help="max cards this session")
    s.add_argument("--all", action="store_true", help="ignore due dates")
    s.add_argument("--no-open", action="store_true"); s.set_defaults(f=cmd_start)

    s = sp.add_parser("sync"); s.set_defaults(f=cmd_sync)
    s = sp.add_parser("record"); s.set_defaults(f=cmd_record)
    s = sp.add_parser("status"); s.add_argument("deck"); s.set_defaults(f=cmd_status)
    s = sp.add_parser("brief"); s.add_argument("deck")
    s.add_argument("--out", default=""); s.set_defaults(f=cmd_brief)

    a = ap.parse_args()
    if getattr(a, "all", False):
        a.new, a.max = 999, 999
    try:
        return a.f(a)
    except DeckError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
